def source_section(source_ids: list[str], sources: dict[str, dict[str, str]]) -> str:
    if not source_ids:
        return "本知识由已列明的上游企业知识派生，不额外挂接外部来源。"
    lines = ["| 来源编号 | 来源 | 适用性 | 使用方式 |", "|---|---|---|---|"]
    for sid in source_ids:
        source = sources[sid]
        usage = "直接适用范围内作为约束" if source["applicability"] == "DIRECT" else "满足适用条件时使用" if source["applicability"] == "CONDITIONAL" else "仅作方法或案例参考"
        lines.append(f"| {sid} | {source['title']} | {source['applicability']} | {usage} |")
    return "\n".join(lines)


