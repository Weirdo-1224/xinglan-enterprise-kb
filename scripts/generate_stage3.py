def main() -> None:
    rows = [row for row in read_csv(MANIFEST) if row["package"] == "PACKAGE-01" and row["knowledge_type"] in RENDERERS]
    sources = {row["source_id"]: row for row in read_csv(REGISTRY)}
    lineage = read_csv(LINEAGE)
    asset_sources: dict[str, list[str]] = {}
    for row in rows:
        kid = row["knowledge_id"]
        linked = [item["source_id"] for item in lineage if item["knowledge_id"] == kid]
        used = [sid for sid, source in sources.items() if kid in split_ids(source["used_by"])]
        linked.extend(POLICY_REQUIRED_SOURCES.get(kid, []))
        if row["knowledge_type"] == "ENTERPRISE_FOUNDATION":
            linked.append("SRC-SYN-001")
        asset_sources[kid] = list(dict.fromkeys(sid for sid in linked + used if sid in sources and sources[sid]["verification_status"] == "VERIFIED"))
    CORE.mkdir(parents=True, exist_ok=True)
    for row in rows:
        meta = metadata(row, asset_sources[row["knowledge_id"]])
        body = RENDERERS[row["knowledge_type"]](row, asset_sources[row["knowledge_id"]], sources)
        text = "---\n" + yaml.safe_dump(meta, allow_unicode=True, sort_keys=False, width=120).strip() + "\n---\n\n" + body.strip() + "\n"
        (CORE / row["filename"]).write_text(text, encoding="utf-8")
    write_claims(rows, asset_sources)
    print(f"Generated {len(rows)} core knowledge files and CLAIM_PROVENANCE.csv")


if __name__ == "__main__":
    main()
